test("a confirmed wontfix move goes through and reads back refused", async () => {
  const directory = await withSnapshot(snapshot([workItem(7, "needs-triage")]));
  const { calls, run } = runStub([{}, ghIssueView({ labels: [{ name: "wontfix" }] })]);
  const handled = await handleWorkflowApi({
    method: "POST",
    pathname: "/api/workflow/triage",
    body: JSON.stringify({ issueId: "GH-7", triageState: "wontfix", confirm: true }),
    appDirectory: directory,
    hostRoot: HOST_ROOT,
    run,
  });
  strictEqual(handled.status, 200);
  strictEqual(calls[0].args[calls[0].args.indexOf("--add-label") + 1], "wontfix");
  strictEqual(handled.json.state.workItems[0].triageState, "wontfix");
});

test("moving parked work un-parks it — deferred rides along on the write", async () => {
  const directory = await withSnapshot(snapshot([workItem(9, "needs-triage", { deferred: true })]));
  const { calls, run } = runStub([
    {},
    ghIssueView({ number: 9, labels: [{ name: "needs-info" }] }),
  ]);
  const handled = await handleWorkflowApi({
    method: "POST",
    pathname: "/api/workflow/triage",
    body: JSON.stringify({ issueId: "GH-9", triageState: "needs-info" }),
    appDirectory: directory,
    hostRoot: HOST_ROOT,
    run,
  });
  strictEqual(handled.status, 200);
  ok(calls[0].args.includes("deferred"), `expected a --remove-label deferred in ${calls[0].args}`);
  strictEqual(handled.json.state.workItems[0].deferred, false);
  strictEqual(handled.json.state.workItems[0].triageState, "needs-info");
});

test("request bodies that fail the schema are rejected naming the path", async () => {
  const directory = await withSnapshot(snapshot([workItem(7)]));
  const cases = [
    [{ issueId: "GH-7", triageState: "wontfix", force: true }, /force/],
    [{ issueId: "GH-7", triageState: "ready" }, /triageState/],
    [{ triageState: "needs-info" }, /issueId/],
    ["{not json", /json/i],
  ];
  for (const [body, pattern] of cases) {
    const { run } = runStub();
    const handled = await handleWorkflowApi({
      method: "POST",
      pathname: "/api/workflow/triage",
      body: typeof body === "string" ? body : JSON.stringify(body),
      appDirectory: directory,
      hostRoot: HOST_ROOT,
      run,
    });
    strictEqual(handled.status, 400);
    ok(pattern.test(handled.json.message), `expected ${handled.json.message} to match ${pattern}`);
  }
});

