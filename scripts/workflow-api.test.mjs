// The generated module's exact shape, as `pnpm sync` writes it.
const generatedModule = (data) =>
  `import type { OverviewData } from './types';\n\n// Generated by pnpm workbench sync. Do not edit by hand.\nexport const overviewData = ${JSON.stringify(data, null, 2)} satisfies OverviewData;\n`;

const withSnapshot = async (data) => {
  const directory = await mkdtemp(join(tmpdir(), "workbench-workflow-"));
  await mkdir(join(directory, "src"), { recursive: true });
  await writeFile(join(directory, "src", "data.generated.ts"), generatedModule(data));
  return directory;
};

// A stubbed `gh`: every invocation is recorded, and the nth call resolves
// from `responses` (a string rejects with it as the tool's stderr, an object
// with a `stdout` key passes through verbatim, anything else is served the
// way `gh --json` prints: JSON-encoded on stdout).
const runStub = (responses = []) => {
  const calls = [];
  const run = async (command, args, cwd) => {
    calls.push({ command, args, cwd });
    const next = responses[calls.length - 1];
    if (typeof next === "string")
      throw Object.assign(new Error(`gh failed: ${next}`), { stderr: next });
    if (next && typeof next === "object" && "stdout" in next) return next;
    return { stdout: JSON.stringify(next ?? null) };
  };
  return { calls, run };
};

const ghIssueView = (overrides = {}) => ({
  number: 7,
  title: "Issue 7",
  url: `https://github.com/${REPO}/issues/7`,
  state: "OPEN",
  assignees: [],
  labels: [{ name: "ready-for-agent" }],
  body: "The body.",
  ...overrides,
});

test("loadWorkflowState imports the generated module across a re-sync", async () => {
  const directory = await withSnapshot(snapshot([workItem(7)]));
  const first = await loadWorkflowState(directory);
  strictEqual(first.workItems[0].id, "GH-7");
  // A re-sync rewrites the same path; the loader must not serve the stale
  // module Node cached on the previous import.
  await writeFile(
    join(directory, "src", "data.generated.ts"),
    generatedModule(snapshot([workItem(8)])),
  );
  const second = await loadWorkflowState(directory);
  strictEqual(second.workItems[0].id, "GH-8");
});

