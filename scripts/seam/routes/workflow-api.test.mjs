test("loadWorkflowState imports the generated module across a re-sync", async () => {
  const directory = await withSnapshot(snapshot([workItem(7)]));
  const first = await loadWorkflowState(directory);
  strictEqual(first.workItems[0].id, "GH-7");
  // A re-sync rewrites the same path; the loader must not serve the stale
  // module Node cached on the previous import.
  await writeFile(
    join(directory, "src", "data.generated.ts"),
    generatedModule(snapshot([workItem(8)])),
  );
  const second = await loadWorkflowState(directory);
  strictEqual(second.workItems[0].id, "GH-8");
});

